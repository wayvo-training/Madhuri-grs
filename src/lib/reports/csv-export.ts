/**
 * Escapes a cell value according to RFC 4180 and protects against Spreadsheet Formula Injection (CWE-1236).
 * Values starting with =, @, \t, \r, or with + / - (not forming pure numbers) have a leading single quote prepended.
 */
export function escapeCsvCell(value: unknown): string {
  if (value === null || value === undefined) {
    return "";
  }
  let str = String(value);

  // Formula Injection Defense (CWE-1236 / CSV Injection)
  // Prevent Excel and other spreadsheets from executing untrusted expressions
  const isFormula =
    /^[=@\t\r]/.test(str) ||
    (/^[-+]/.test(str) && !/^[-+]?\d+(?:\.\d+)?$/.test(str));

  if (isFormula) {
    str = `'${str}`;
  }

  // RFC 4180: If cell contains quotes, commas, or line breaks, or starts with single quote, enclose in quotes and double internal quotes
  if (/[",\r\n]/.test(str) || str.startsWith("'")) {
    return `"${str.replace(/"/g, '""')}"`;
  }

  return str;
}

/**
 * Formats an array of values into a valid RFC 4180 CSV row with CRLF line ending.
 */
export function formatCsvRow(row: unknown[]): string {
  return `${row.map(escapeCsvCell).join(",")}\r\n`;
}

/**
 * Formats an applied filters summary string for report metadata.
 */
function formatFiltersSummary(filters?: object): string {
  if (!filters || Object.keys(filters).length === 0) {
    return "None (Default Parameters)";
  }
  const pairs: string[] = [];
  for (const [key, val] of Object.entries(filters)) {
    if (val !== undefined && val !== null && val !== "") {
      pairs.push(`${key}: ${String(val)}`);
    }
  }
  return pairs.length > 0 ? pairs.join("; ") : "None (Default Parameters)";
}

/**
 * Builds CSV for Operational Reports (LLD §3.10.2).
 */
export function buildOperationalReportCsv(
  data: OperationalReportData,
  filters?: OperationalReportFilters,
): string {
  let csv = "";

  // 1. Report Metadata
  csv += formatCsvRow([
    "REPORT TITLE",
    "Grievance Redressal System - Operational Report",
  ]);
  csv += formatCsvRow([
    "SCOPE",
    data.metadata.scope.isOrganizationWide
      ? "Organization-Wide"
      : data.metadata.scope.departmentName || "Department Scoped",
  ]);
  csv += formatCsvRow([
    "REPORTING PERIOD",
    data.metadata.reportingPeriod.label,
  ]);
  csv += formatCsvRow(["GENERATED AT", data.metadata.generatedAt]);
  csv += formatCsvRow([
    "GENERATED BY",
    `${data.metadata.generatedBy.name} (${data.metadata.generatedBy.role})`,
  ]);
  csv += formatCsvRow(["APPLIED FILTERS", formatFiltersSummary(filters)]);
  csv += formatCsvRow(["GOVERNANCE REFERENCE", "GRS LLD Section 3.10.2"]);
  csv += "\r\n";

  // 2. Volume Summary
  csv += formatCsvRow(["=== VOLUME SUMMARY ==="]);
  csv += formatCsvRow(["Metric", "Count"]);
  csv += formatCsvRow([
    "Total Unique Grievances",
    data.summary.totalUniqueGrievances,
  ]);
  csv += formatCsvRow(["Active Grievances", data.summary.activeGrievances]);
  csv += formatCsvRow(["Resolved Grievances", data.summary.resolvedGrievances]);
  csv += formatCsvRow(["Closed Grievances", data.summary.closedGrievances]);
  csv += formatCsvRow([
    "SLA Breached Grievances",
    data.summary.slaBreachedGrievances,
  ]);
  csv += formatCsvRow([
    "SLA Approaching Grievances",
    data.summary.slaApproachingGrievances,
  ]);
  csv += formatCsvRow([
    "Escalated Grievances",
    data.summary.escalatedGrievances,
  ]);
  csv += formatCsvRow([
    "Unassigned Grievances",
    data.summary.unassignedGrievances,
  ]);
  csv += "\r\n";

  // 3. Status Distribution
  csv += formatCsvRow(["=== STATUS DISTRIBUTION ==="]);
  csv += formatCsvRow(["Status", "Count", "Percentage (%)"]);
  for (const s of data.statusDistribution) {
    csv += formatCsvRow([s.status, s.count, `${s.percentage}%`]);
  }
  csv += "\r\n";

  // 4. Department Workload Distribution
  csv += formatCsvRow(["=== DEPARTMENT WORKLOAD DISTRIBUTION ==="]);
  csv += formatCsvRow([
    "Department Name",
    "Primary Grievance Count",
    "Supporting Grievance Count",
    "Total Grievance Involvement",
    "Percentage of Total (%)",
  ]);
  for (const d of data.departmentDistribution) {
    csv += formatCsvRow([
      d.departmentName,
      d.primaryCount,
      d.supportingCount,
      d.totalInvolvement,
      `${d.percentageOfTotal}%`,
    ]);
  }
  csv += "\r\n";

  // 5. Category & Subcategory Breakdown
  csv += formatCsvRow(["=== CATEGORY & SUBCATEGORY BREAKDOWN ==="]);
  csv += formatCsvRow([
    "Category Name",
    "Subcategory Name",
    "Count",
    "Percentage (%)",
  ]);
  for (const c of data.categoryDistribution) {
    for (const sub of c.subcategories) {
      csv += formatCsvRow([
        c.categoryName,
        sub.subcategoryName,
        sub.count,
        `${sub.percentage}%`,
      ]);
    }
  }
  csv += "\r\n";

  // 6. Priority Distribution
  csv += formatCsvRow(["=== PRIORITY DISTRIBUTION ==="]);
  csv += formatCsvRow(["Priority", "Count", "Percentage (%)"]);
  for (const p of data.priorityDistribution) {
    csv += formatCsvRow([p.priority, p.count, `${p.percentage}%`]);
  }
  csv += "\r\n";

  // 7. Staff Assignments Workload
  csv += formatCsvRow(["=== CURRENT STAFF WORKLOAD ASSIGNMENTS ==="]);
  csv += formatCsvRow([
    "Staff Name",
    "Email",
    "Department",
    "Active Assigned Cases",
  ]);
  for (const staff of data.staffAssignments.currentStaffWorkload) {
    csv += formatCsvRow([
      staff.staffName,
      staff.email,
      staff.departmentName,
      staff.activeAssignmentsCount,
    ]);
  }
  csv += "\r\n";

  // 8. SLA Health Monitoring (Breached & Approaching)
  csv += formatCsvRow(["=== SLA HEALTH MONITORING (AT-RISK & BREACHED) ==="]);
  csv += formatCsvRow([
    "Grievance Number",
    "Title",
    "Department",
    "Priority",
    "SLA Status",
    "Workflow Status",
    "Due Date",
  ]);
  for (const g of [
    ...data.slaMonitoring.breachedGrievances,
    ...data.slaMonitoring.approachingGrievances,
  ]) {
    csv += formatCsvRow([
      g.grievanceNumber,
      g.title,
      g.primaryDepartmentName,
      g.priority,
      g.slaStatus,
      g.status,
      g.dueAt || "N/A",
    ]);
  }
  csv += "\r\n";

  // 9. Escalations
  csv += formatCsvRow(["=== ESCALATION RECORDS ==="]);
  csv += formatCsvRow([
    "Grievance Number",
    "Title",
    "Escalation Level",
    "Escalated To",
    "Reason",
    "Status",
    "Date",
  ]);
  for (const e of data.escalations.events) {
    csv += formatCsvRow([
      e.grievanceNumber,
      e.grievanceTitle,
      `Level ${e.escalationLevel}`,
      e.escalatedToName,
      e.reason,
      e.status,
      e.createdAt,
    ]);
  }

  return csv;
}

/**
 * Builds CSV for Resolution Analytics (TAT) Reports (LLD §3.10.3).
 */
export function buildResolutionAnalyticsCsv(
  data: ResolutionAnalyticsData,
  filters?: ResolutionAnalyticsFilters,
): string {
  let csv = "";

  // 1. Report Metadata
  csv += formatCsvRow([
    "REPORT TITLE",
    "Grievance Redressal System - Resolution Analytics (TAT) Report",
  ]);
  csv += formatCsvRow([
    "SCOPE",
    data.metadata.scope.isOrganizationWide
      ? "Organization-Wide"
      : data.metadata.scope.departmentName || "Department Scoped",
  ]);
  csv += formatCsvRow([
    "REPORTING PERIOD",
    data.metadata.reportingPeriod.label,
  ]);
  csv += formatCsvRow(["GENERATED AT", data.metadata.generatedAt]);
  csv += formatCsvRow([
    "GENERATED BY",
    `${data.metadata.generatedBy.name} (${data.metadata.generatedBy.role})`,
  ]);
  csv += formatCsvRow(["APPLIED FILTERS", formatFiltersSummary(filters)]);
  csv += formatCsvRow(["GOVERNANCE REFERENCE", "GRS LLD Section 3.10.3"]);
  csv += "\r\n";

  // 2. End-to-End TAT Overview
  csv += formatCsvRow(["=== END-TO-END RESOLUTION TIME (OVERALL TAT) ==="]);
  csv += formatCsvRow(["Metric", "Value"]);
  csv += formatCsvRow([
    "Average End-to-End TAT (Hours)",
    data.overview.avgResolutionTimeHours,
  ]);
  csv += formatCsvRow([
    "Median End-to-End TAT (Hours)",
    data.overview.medianResolutionTimeHours,
  ]);
  csv += formatCsvRow([
    "Average End-to-End TAT (Days)",
    data.overview.avgResolutionTimeDays,
  ]);
  csv += formatCsvRow([
    "Median End-to-End TAT (Days)",
    data.overview.medianResolutionTimeDays,
  ]);
  csv += formatCsvRow(["Total Closed Grievances", data.overview.totalClosed]);
  csv += formatCsvRow([
    "Closed with Authoritative TAT",
    data.overview.closedWithValidTat,
  ]);
  csv += formatCsvRow([
    "Data Quality Exceptions (Missing closed_at)",
    data.overview.dataQualityExceptionsCount,
  ]);
  csv += formatCsvRow([
    "SLA Compliance Rate (%)",
    `${data.overview.slaComplianceRate}%`,
  ]);
  csv += formatCsvRow(["Total SLA Breaches", data.overview.totalSlaBreaches]);
  csv += "\r\n";

  // 3. Departmental Processing Durations
  csv += formatCsvRow(["=== DEPARTMENTAL PROCESSING DURATIONS ==="]);
  csv += formatCsvRow([
    "Department Name",
    "Total Involved",
    "Completed Stages",
    "Valid Duration Stages",
    "Avg Duration (Hours)",
    "Median Duration (Hours)",
    "Avg Primary Hours",
    "Avg Supporting Hours",
    "SLA Compliance Rate (%)",
  ]);
  for (const d of data.departmentProcessing) {
    csv += formatCsvRow([
      d.departmentName,
      d.totalInvolved,
      d.completedStagesCount,
      d.completedWithValidDurationCount,
      d.avgProcessingTimeHours,
      d.medianProcessingTimeHours,
      d.avgPrimaryProcessingHours,
      d.avgSupportingProcessingHours,
      `${d.slaComplianceRate}%`,
    ]);
  }
  csv += "\r\n";

  // 4. SLA Compliance & Cycles
  csv += formatCsvRow(["=== SLA COMPLIANCE BY RESOLUTION CYCLE ==="]);
  csv += formatCsvRow([
    "Cycle Type",
    "Cycle Label",
    "Total Completed Cycles",
    "Compliant Cycles",
    "Breached Cycles",
    "SLA Compliance Rate (%)",
    "Avg Paused Minutes",
  ]);
  for (const c of data.slaCompliance.byCycleType) {
    csv += formatCsvRow([
      c.cycleType,
      c.label,
      c.totalCompletedCycles,
      c.compliantCycles,
      c.breachedCycles,
      `${c.complianceRate}%`,
      c.avgPausedMinutes,
    ]);
  }
  csv += "\r\n";

  // 5. Reopening & Rework TAT
  csv += formatCsvRow(["=== REOPENING & REWORK BREAKDOWN ==="]);
  csv += formatCsvRow(["Metric", "Value"]);
  csv += formatCsvRow([
    "Reopened Grievance Rate",
    `${data.reworkAndReopen.reopenedRate}%`,
  ]);
  csv += formatCsvRow([
    "Reopened Grievances Count",
    data.reworkAndReopen.reopenedGrievancesCount,
  ]);
  csv += formatCsvRow([
    "Total Reopen Attempts",
    data.reworkAndReopen.totalReopenAttempts,
  ]);
  csv += formatCsvRow([
    "Rework Review Rejections",
    data.reworkAndReopen.reworkReviewRejectionsCount,
  ]);
  csv += formatCsvRow([
    "Multi-Resolution Grievances",
    data.reworkAndReopen.multiResolutionGrievancesCount,
  ]);
  csv += "\r\n";

  // 6. Resolution TAT by Priority
  csv += formatCsvRow(["=== RESOLUTION TAT BY PRIORITY ==="]);
  csv += formatCsvRow([
    "Priority",
    "Total Cases",
    "Closed Cases",
    "Valid TAT Cases",
    "Missing closed_at Exceptions",
    "Avg TAT (Hours)",
    "Median TAT (Hours)",
    "SLA Compliance Rate (%)",
  ]);
  for (const p of data.tatByPriority) {
    csv += formatCsvRow([
      p.priority,
      p.totalGrievances,
      p.closedCount,
      p.closedWithValidTat,
      p.missingClosedAtCount,
      p.avgResolutionTimeHours,
      p.medianResolutionTimeHours,
      `${p.slaComplianceRate}%`,
    ]);
  }
  csv += "\r\n";

  // 7. Resolution Lifecycle Stages
  csv += formatCsvRow(["=== RESOLUTION LIFECYCLE STAGES ==="]);
  csv += formatCsvRow([
    "Stage",
    "Label",
    "Grievance Count",
    "Percentage (%)",
    "Description",
  ]);
  for (const s of data.stages) {
    csv += formatCsvRow([
      s.stage,
      s.label,
      s.count,
      `${s.percentage}%`,
      s.description,
    ]);
  }

  return csv;
}

/**
 * Builds CSV for Trend & Recurring Pattern Detection Reports (LLD §3.10.5).
 */
export function buildPatternDetectionCsv(
  data: PatternDetectionData,
  filters?: PatternFilters,
): string {
  let csv = "";

  // 1. Report Metadata
  csv += formatCsvRow([
    "REPORT TITLE",
    "Grievance Redressal System - Trend & Recurring Pattern Analysis Report",
  ]);
  csv += formatCsvRow([
    "SCOPE",
    data.metadata.scope.isOrganizationWide
      ? "Organization-Wide"
      : data.metadata.scope.departmentName || "Department Scoped",
  ]);
  csv += formatCsvRow(["ANALYSIS WINDOW", data.metadata.reportingPeriod.label]);
  csv += formatCsvRow(["GENERATED AT", data.metadata.generatedAt]);
  csv += formatCsvRow([
    "GENERATED BY",
    `${data.metadata.generatedBy.name} (${data.metadata.generatedBy.role})`,
  ]);
  csv += formatCsvRow(["APPLIED FILTERS", formatFiltersSummary(filters)]);
  csv += formatCsvRow(["GOVERNANCE REFERENCE", "GRS LLD Section 3.10.5"]);
  csv += formatCsvRow([
    "POLICY NOTICE",
    "Notice: Recurring patterns indicate descriptive high-frequency issue clusters and are distinguished from confirmed root causes. Pattern alerts do not trigger automated system changes.",
  ]);
  csv += "\r\n";

  // 2. Pattern Summary Metrics
  csv += formatCsvRow(["=== PATTERN SUMMARY METRICS ==="]);
  csv += formatCsvRow(["Metric", "Value"]);
  csv += formatCsvRow([
    "Total Patterns Detected",
    data.summary.totalPatternsDetected,
  ]);
  csv += formatCsvRow([
    "Total Affected Cases",
    data.summary.totalAffectedGrievances,
  ]);
  csv += formatCsvRow([
    "Impacted Departments Count",
    data.summary.departmentsWithPatternsCount,
  ]);
  csv += formatCsvRow([
    "Total Cases in 30-Day Window",
    data.summary.totalGrievancesInWindow,
  ]);
  csv += formatCsvRow([
    "Clustering Threshold Rule",
    `> ${data.summary.minThreshold} cases in 30 calendar days`,
  ]);
  csv += formatCsvRow([
    "Data Sufficiency Status",
    data.summary.isInsufficientData
      ? "Insufficient Data (< 5 cases in window)"
      : "Sufficient Data",
  ]);
  csv += "\r\n";

  // 3. Recurring Category Patterns (LLD §3.10.5)
  csv += formatCsvRow(["=== RECURRING CATEGORY PATTERNS (LLD §3.10.5) ==="]);
  csv += formatCsvRow([
    "Department Name",
    "Category Name",
    "Matching Volume",
    "Threshold Rule",
    "Severity",
    "Contributing Subcategories Breakdown",
    "Analysis Period",
  ]);
  for (const p of data.categoryPatterns) {
    const subStr = p.subcategoriesInvolved
      .map((s) => `${s.subcategoryName} (${s.count})`)
      .join("; ");
    csv += formatCsvRow([
      p.departmentName,
      p.categoryName,
      p.matchingCount,
      `> ${p.threshold}`,
      p.severity,
      subStr,
      p.analysisPeriod.label,
    ]);
  }
  csv += "\r\n";

  // 4. Contributing Grievance Records (Drilldown)
  csv += formatCsvRow(["=== CONTRIBUTING GRIEVANCE DRILLDOWN RECORDS ==="]);
  csv += formatCsvRow([
    "Pattern Category",
    "Department",
    "Grievance Number",
    "Title",
    "Subcategory",
    "Priority",
    "Status",
    "Submitted Date",
  ]);
  for (const p of data.categoryPatterns) {
    for (const g of p.associatedGrievances) {
      csv += formatCsvRow([
        p.categoryName,
        p.departmentName,
        g.grievanceNumber,
        g.title,
        g.subcategoryName,
        g.priority,
        g.status,
        g.createdAt,
      ]);
    }
  }
  csv += "\r\n";

  // 5. Duplicate Clusters & Schema Limitation
  csv += formatCsvRow(["=== DUPLICATE CLUSTERS (LLD §3.10.5) ==="]);
  csv += formatCsvRow(["Status", "Limitation Documented"]);
  csv += formatCsvRow(["Schema Limitation Notice", data.dataLimitationNotice]);

  return csv;
}

/**
 * Generates CSV content and metadata for the requested report type using authoritative data services.
 */
export async function generateReportCsv(
  reportType: "OPERATIONAL" | "RESOLUTION" | "PATTERNS",
  filters: Record<string, string | undefined>,
  user: AuthUser,
): Promise<{
  csvContent: string;
  fileName: string;
  recordCount: number;
}> {
  const timestamp = new Date()
    .toISOString()
    .replace(/[-:]/g, "")
    .replace("T", "_")
    .slice(0, 15);

  switch (reportType) {
    case "OPERATIONAL": {
      const opFilters: OperationalReportFilters = {
        startDate: filters.startDate,
        endDate: filters.endDate,
        departmentId: filters.departmentId,
        categoryId: filters.categoryId,
        subcategoryId: filters.subcategoryId,
        priority: filters.priority,
        status: filters.status,
        slaStatus: filters.slaStatus,
        assignmentStatus:
          filters.assignmentStatus as OperationalReportFilters["assignmentStatus"],
      };

      const data = await generateOperationalReport(opFilters, user);
      const csvContent = buildOperationalReportCsv(data, opFilters);
      const fileName = `GRS_Operational_Report_${timestamp}.csv`;
      const recordCount = data.summary.totalUniqueGrievances;

      return { csvContent, fileName, recordCount };
    }

    case "RESOLUTION": {
      const resFilters: ResolutionAnalyticsFilters = {
        startDate: filters.startDate,
        endDate: filters.endDate,
        departmentId: filters.departmentId,
        categoryId: filters.categoryId,
        subcategoryId: filters.subcategoryId,
        priority: filters.priority,
      };

      const response = await generateResolutionAnalytics(resFilters, user);
      if (!response.success || !response.data) {
        throw new Error(
          response.message || "Failed to generate resolution analytics report",
        );
      }
      const data = response.data;
      const csvContent = buildResolutionAnalyticsCsv(data, resFilters);
      const fileName = `GRS_Resolution_Analytics_${timestamp}.csv`;
      const recordCount = data.overview.totalClosed;

      return { csvContent, fileName, recordCount };
    }

    case "PATTERNS": {
      const patFilters: PatternFilters = {
        startDate: filters.startDate,
        endDate: filters.endDate,
        departmentId: filters.departmentId,
        categoryId: filters.categoryId,
        priority: filters.priority,
      };

      const data = await generatePatternDetectionReport(patFilters, user);
      const csvContent = buildPatternDetectionCsv(data, patFilters);
      const fileName = `GRS_Pattern_Analysis_${timestamp}.csv`;
      const recordCount = data.summary.totalAffectedGrievances;

      return { csvContent, fileName, recordCount };
    }

    default:
      throw new Error(`Unsupported report type: ${String(reportType)}`);
  }
}
