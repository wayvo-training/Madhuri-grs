/**
 * Sanitizes untrusted cell values to prevent Spreadsheet Formula Injection (CWE-1236).
 * Values starting with =, @, \t, \r, or +/- (not forming a pure number) have a leading single quote prepended.
 */
export function sanitizeExcelText(value: unknown): string {
  if (value === null || value === undefined) {
    return "";
  }
  let str = String(value);

  const isFormula =
    /^[=@\t\r]/.test(str) ||
    (/^[-+]/.test(str) && !/^[-+]?\d+(?:\.\d+)?$/.test(str));

  if (isFormula) {
    str = `'${str}`;
  }

  return str;
}

/**
 * Formats filter summary for the metadata section.
 */
function formatFiltersSummary(filters?: object): string {
  if (!filters || Object.keys(filters).length === 0) {
    return "None (Default Parameters)";
  }
  const pairs: string[] = [];
  for (const [key, val] of Object.entries(filters)) {
    if (val !== undefined && val !== null && val !== "") {
      pairs.push(`${key}: ${String(val)}`);
    }
  }
  return pairs.length > 0 ? pairs.join("; ") : "None (Default Parameters)";
}

/**
 * Helper to auto-fit worksheet columns within reasonable bounds.
 */
function autoFitWorksheetColumns(sheet: ExcelJS.Worksheet) {
  sheet.columns.forEach((column) => {
    let maxLength = 12;
    column.eachCell?.({ includeEmpty: true }, (cell) => {
      const cellLength = cell.value ? String(cell.value).length : 0;
      if (cellLength > maxLength) {
        maxLength = cellLength;
      }
    });
    column.width = Math.min(Math.max(maxLength + 3, 14), 45);
  });
}

/**
 * Formats a header row with standard fill, font, and frozen view.
 */
function applyHeaderRowStyle(
  sheet: ExcelJS.Worksheet,
  rowNumber: number,
  freeze = true,
) {
  const row = sheet.getRow(rowNumber);
  row.eachCell((cell) => {
    cell.fill = HEADER_FILL;
    cell.font = HEADER_FONT;
    cell.alignment = { vertical: "middle" };
    cell.border = BORDER_THIN;
  });
  row.height = 24;

  if (freeze) {
    sheet.views = [{ state: "frozen", xSplit: 0, ySplit: rowNumber }];
  }
}

