/**
 * Sanitizes strings for standard PDFKit Helvetica (Windows-1252 / ISO-8859-1 compatible).
 */
export function cleanPdfText(val: unknown): string {
  if (val === null || val === undefined) return "";
  let str = String(val);

  // Normalize common Unicode symbols into clean ASCII equivalents
  str = str
    .replace(/[—–]/g, "-")
    .replace(/[""]/g, '"')
    .replace(/['']/g, "'")
    .replace(/•/g, "*")
    .replace(/≥/g, ">=")
    .replace(/≤/g, "<=")
    .replace(/→/g, "->")
    .replace(/…/g, "...")
    .replace(/[\r\n]+/g, " ");

  // Strip non-printable or unsupported control characters
  return str.replace(/[^\x20-\x7E\xA0-\xFF]/g, "");
}

/**
 * Formats filter summary into human-readable string.
 */
function formatFiltersSummary(filters?: object): string {
  if (!filters || Object.keys(filters).length === 0) {
    return "None (Default Parameters)";
  }
  const pairs: string[] = [];
  for (const [key, val] of Object.entries(filters)) {
    if (val !== undefined && val !== null && val !== "") {
      pairs.push(`${key}: ${String(val)}`);
    }
  }
  return pairs.length > 0 ? pairs.join("; ") : "None (Default Parameters)";
}

/**
 * Draws top banner, title, and metadata header grid.
 */
function drawHeaderBanner(
  doc: PDFKit.PDFDocument,
  title: string,
  lldRef: string,
  scope: string,
  reportingPeriod: string,
  generatedAt: string,
  generatedBy: string,
  filtersStr: string,
): number {
  let y = MARGIN;

  // 1. Accent color bar
  doc.rect(MARGIN, y, PRINTABLE_WIDTH, 4).fill(COLOR_ACCENT);
  y += 12;

  // 2. Report Title & LLD Reference Badge
  doc.fillColor(COLOR_TITLE).fontSize(14).font("Helvetica-Bold");
  doc.text(title, MARGIN, y);

  doc.fillColor(COLOR_MUTED).fontSize(8).font("Helvetica");
  doc.text(`Governance: ${lldRef} · Scope: ${scope}`, MARGIN, y + 18);
  y += 34;

  // 3. Metadata 2x2 Grid Box
  const boxWidth = PRINTABLE_WIDTH;
  const boxHeight = 44;
  doc
    .roundedRect(MARGIN, y, boxWidth, boxHeight, 4)
    .fillAndStroke("#f8fafc", COLOR_BORDER_LIGHT);

  const col1 = MARGIN + 12;
  const col2 = MARGIN + 260;
  const col3 = MARGIN + 510;

  // Row 1
  doc.fillColor(COLOR_MUTED).fontSize(7.5).font("Helvetica-Bold");
  doc.text("REPORTING PERIOD:", col1, y + 8);
  doc.fillColor(COLOR_TEXT).font("Helvetica");
  doc.text(reportingPeriod, col1 + 86, y + 8, { width: 155 });

  doc.fillColor(COLOR_MUTED).font("Helvetica-Bold");
  doc.text("GENERATED AT:", col2, y + 8);
  doc.fillColor(COLOR_TEXT).font("Helvetica");
  doc.text(generatedAt, col2 + 70, y + 8, { width: 170 });

  doc.fillColor(COLOR_MUTED).font("Helvetica-Bold");
  doc.text("GENERATED BY:", col3, y + 8);
  doc.fillColor(COLOR_TEXT).font("Helvetica");
  doc.text(generatedBy, col3 + 70, y + 8, { width: 170 });

  // Row 2
  doc.fillColor(COLOR_MUTED).font("Helvetica-Bold");
  doc.text("APPLIED FILTERS:", col1, y + 24);
  doc.fillColor(COLOR_TEXT).font("Helvetica");
  doc.text(cleanPdfText(filtersStr), col1 + 86, y + 24, { width: 650 });

  return y + boxHeight + 14;
}

/**
 * Draws a section header with an underline indicator.
 */
function drawSectionHeading(
  doc: PDFKit.PDFDocument,
  title: string,
  currentY: number,
): number {
  let y = currentY;
  if (y > CONTENT_BOTTOM_LIMIT - 50) {
    doc.addPage({ size: "A4", layout: "landscape", margin: MARGIN });
    y = MARGIN + 10;
  }

  doc.fillColor(COLOR_ACCENT).rect(MARGIN, y, 3, 13).fill();

  doc.fillColor(COLOR_TITLE).fontSize(10).font("Helvetica-Bold");
  doc.text(title, MARGIN + 8, y + 1);

  y += 18;
  doc.strokeColor(COLOR_BORDER_LIGHT).lineWidth(0.5);
  doc
    .moveTo(MARGIN, y)
    .lineTo(MARGIN + PRINTABLE_WIDTH, y)
    .stroke();

  return y + 8;
}

/**
 * Draws a horizontal row of summary metric cards.
 */
function drawMetricCards(
  doc: PDFKit.PDFDocument,
  cards: Array<{ label: string; value: string | number; color?: string }>,
  currentY: number,
): number {
  let y = currentY;
  if (y > CONTENT_BOTTOM_LIMIT - 45) {
    doc.addPage({ size: "A4", layout: "landscape", margin: MARGIN });
    y = MARGIN + 10;
  }

  const gap = 8;
  const count = cards.length;
  const cardWidth = (PRINTABLE_WIDTH - gap * (count - 1)) / count;
  const cardHeight = 36;

  cards.forEach((card, index) => {
    const cardX = MARGIN + index * (cardWidth + gap);

    doc
      .roundedRect(cardX, y, cardWidth, cardHeight, 3)
      .fillAndStroke("#ffffff", COLOR_BORDER_LIGHT);

    doc.fillColor(COLOR_MUTED).fontSize(6.8).font("Helvetica-Bold");
    doc.text(cleanPdfText(card.label).toUpperCase(), cardX + 6, y + 6, {
      width: cardWidth - 12,
      ellipsis: true,
    });

    const valColor = card.color || COLOR_TITLE;
    doc.fillColor(valColor).fontSize(12).font("Helvetica-Bold");
    doc.text(String(card.value), cardX + 6, y + 18, {
      width: cardWidth - 12,
      ellipsis: true,
    });
  });

  return y + cardHeight + 12;
}

export interface TableColumnConfig {
  header: string;
  width: number;
  align?: "left" | "center" | "right";
}

/**
 * Universal multi-page table drawer with repeated headers, alternating zebra fills, and word-wrapping.
 */
function drawTable(
  doc: PDFKit.PDFDocument,
  columns: TableColumnConfig[],
  rows: (string | number)[][],
  startY: number,
  emptyMessage = "No records found matching the specified parameters.",
): number {
  let y = startY;

  const renderHeader = (headerY: number): number => {
    doc.rect(MARGIN, headerY, PRINTABLE_WIDTH, 18).fill(COLOR_HEADER_BG);
    doc.rect(MARGIN, headerY, PRINTABLE_WIDTH, 18).stroke(COLOR_BORDER);

    let x = MARGIN;
    doc.fillColor(COLOR_TITLE).fontSize(7.5).font("Helvetica-Bold");

    for (const col of columns) {
      const align = col.align || "left";
      doc.text(col.header, x + 4, headerY + 5, {
        width: col.width - 8,
        align,
        ellipsis: true,
      });
      x += col.width;
    }
    return headerY + 18;
  };

  // Check if header fits on current page
  if (y > CONTENT_BOTTOM_LIMIT - 40) {
    doc.addPage({ size: "A4", layout: "landscape", margin: MARGIN });
    y = MARGIN + 10;
  }

  y = renderHeader(y);

  if (rows.length === 0) {
    doc
      .rect(MARGIN, y, PRINTABLE_WIDTH, 20)
      .fillAndStroke("#ffffff", COLOR_BORDER_LIGHT);
    doc.fillColor(COLOR_MUTED).fontSize(7.5).font("Helvetica-Oblique");
    doc.text(emptyMessage, MARGIN + 10, y + 6, {
      width: PRINTABLE_WIDTH - 20,
      align: "center",
    });
    return y + 28;
  }

  // Render Rows
  rows.forEach((row, rowIndex) => {
    // 1. Calculate row height based on text wrapping
    let maxCellHeight = 14;
    doc.fontSize(7.2).font("Helvetica");

    row.forEach((cellVal, colIdx) => {
      const col = columns[colIdx];
      if (!col) return;
      const cellText = cleanPdfText(cellVal);
      const textHeight = doc.heightOfString(cellText, {
        width: col.width - 8,
      });
      if (textHeight > maxCellHeight) {
        maxCellHeight = textHeight;
      }
    });

    const rowHeight = maxCellHeight + 6;

    // 2. Check for page overflow
    if (y + rowHeight > CONTENT_BOTTOM_LIMIT) {
      doc.addPage({ size: "A4", layout: "landscape", margin: MARGIN });
      y = MARGIN + 10;
      y = renderHeader(y);
    }

    // 3. Draw row background
    const isAlt = rowIndex % 2 === 1;
    doc
      .rect(MARGIN, y, PRINTABLE_WIDTH, rowHeight)
      .fillAndStroke(isAlt ? COLOR_ROW_ALT : "#ffffff", COLOR_BORDER_LIGHT);

    // 4. Render cell texts
    let x = MARGIN;
    doc.fillColor(COLOR_TEXT).fontSize(7.2).font("Helvetica");

    row.forEach((cellVal, colIdx) => {
      const col = columns[colIdx];
      if (!col) return;
      const cellText = cleanPdfText(cellVal);
      const align = col.align || "left";

      doc.text(cellText, x + 4, y + 4, {
        width: col.width - 8,
        align,
      });
      x += col.width;
    });

    y += rowHeight;
  });

  return y + 12;
}

/**
 * Adds running headers, footers and accurate "Page X of Y" numbers across all buffered pages.
 */
function addHeadersAndFooters(doc: PDFKit.PDFDocument, reportTitle: string) {
  const range = doc.bufferedPageRange();
  const totalPages = range.count;

  for (let i = range.start; i < range.start + totalPages; i++) {
    doc.switchToPage(i);

    // Running Header (Pages > 1)
    if (i > range.start) {
      doc.fillColor(COLOR_MUTED).fontSize(7).font("Helvetica");
      doc.text(
        `GRS Enterprise Reporting · ${reportTitle} · Confidential Audit Document`,
        MARGIN,
        18,
      );
      doc.strokeColor(COLOR_BORDER_LIGHT).lineWidth(0.5);
      doc
        .moveTo(MARGIN, 28)
        .lineTo(MARGIN + PRINTABLE_WIDTH, 28)
        .stroke();
    }

    // Running Footer
    doc.strokeColor(COLOR_BORDER_LIGHT).lineWidth(0.5);
    doc
      .moveTo(MARGIN, PAGE_HEIGHT - 28)
      .lineTo(MARGIN + PRINTABLE_WIDTH, PAGE_HEIGHT - 28)
      .stroke();

    doc.fillColor(COLOR_MUTED).fontSize(7).font("Helvetica");
    doc.text(
      "Grievance Redressal System (GRS) · Authoritative Audit Export (LLD Section 4.7)",
      MARGIN,
      PAGE_HEIGHT - 22,
    );

    const pageStr = `Page ${i - range.start + 1} of ${totalPages}`;
    doc.text(pageStr, MARGIN, PAGE_HEIGHT - 22, {
      width: PRINTABLE_WIDTH,
      align: "right",
    });
  }
}

