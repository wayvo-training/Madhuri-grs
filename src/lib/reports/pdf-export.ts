// ==========================================
// 4. MAIN EXPORT DISPATCHER
// ==========================================

export async function generateReportPdf(
  reportType: "OPERATIONAL" | "RESOLUTION" | "PATTERNS",
  filters: Record<string, string | undefined>,
  user: AuthUser,
): Promise<{
  buffer: Buffer;
  fileName: string;
  recordCount: number;
}> {
  const timestamp = new Date()
    .toISOString()
    .replace(/[-:]/g, "")
    .replace("T", "_")
    .slice(0, 15);

  const doc = new PDFDocument({
    size: "A4",
    layout: "landscape",
    margin: MARGIN,
    bufferPages: true,
  });

  const buffers: Buffer[] = [];
  doc.on("data", (chunk: Buffer) => buffers.push(chunk));

  let fileName: string;
  let recordCount: number;

  switch (reportType) {
    case "OPERATIONAL": {
      const opFilters: OperationalReportFilters = {
        startDate: filters.startDate,
        endDate: filters.endDate,
        departmentId: filters.departmentId,
        categoryId: filters.categoryId,
        subcategoryId: filters.subcategoryId,
        priority: filters.priority,
        status: filters.status,
        slaStatus: filters.slaStatus,
        assignmentStatus:
          filters.assignmentStatus as OperationalReportFilters["assignmentStatus"],
      };

      const data = await generateOperationalReport(opFilters, user);
      await buildOperationalReportPdf(doc, data, opFilters);
      fileName = `GRS_Operational_Report_${timestamp}.pdf`;
      recordCount = data.summary.totalUniqueGrievances;
      break;
    }

    case "RESOLUTION": {
      const resFilters: ResolutionAnalyticsFilters = {
        startDate: filters.startDate,
        endDate: filters.endDate,
        departmentId: filters.departmentId,
        categoryId: filters.categoryId,
        subcategoryId: filters.subcategoryId,
        priority: filters.priority,
      };

      const response = await generateResolutionAnalytics(resFilters, user);
      if (!response.success || !response.data) {
        throw new Error(
          response.message || "Failed to generate resolution analytics report",
        );
      }
      await buildResolutionAnalyticsPdf(doc, response.data, resFilters);
      fileName = `GRS_Resolution_Analytics_${timestamp}.pdf`;
      recordCount = response.data.overview.totalClosed;
      break;
    }

    case "PATTERNS": {
      const patFilters: PatternFilters = {
        startDate: filters.startDate,
        endDate: filters.endDate,
        departmentId: filters.departmentId,
        categoryId: filters.categoryId,
        priority: filters.priority,
      };

      const data = await generatePatternDetectionReport(patFilters, user);
      await buildPatternDetectionPdf(doc, data, patFilters);
      fileName = `GRS_Pattern_Analysis_${timestamp}.pdf`;
      recordCount = data.summary.totalAffectedGrievances;
      break;
    }

    default:
      throw new Error(`Unsupported report type: ${String(reportType)}`);
  }

  // Finalize PDFKit document stream
  doc.end();

  const buffer = await new Promise<Buffer>((resolve, reject) => {
    doc.on("end", () => resolve(Buffer.concat(buffers)));
    doc.on("error", (err) => reject(err));
  });

  return {
    buffer,
    fileName,
    recordCount,
  };
}
